def quoted(columns, prefix=''):
    return ', '.join(f'{prefix}`{c}`' for c in columns)


def row_json(columns, prefix):
    return 'JSON_OBJECT(' + ', '.join(f"'{c}', {prefix}`{c}`" for c in columns) + ')'


HEADER = """-- Generated by scripts/generate_temporal_history.py from the version-4 model.
-- Stop application writes and take a backup before applying this DDL migration.
-- Snapshots observe existing state; they do not invent past actors or valid-from times.
CREATE TABLE TemporalWriteContext (
    ConnectionID BIGINT UNSIGNED NOT NULL,
    SessionAccount VARCHAR(288) COLLATE utf8mb4_bin NOT NULL,
    EntityType VARCHAR(64) NOT NULL,
    PRIMARY KEY (ConnectionID, EntityType)
) ENGINE=InnoDB;

-- An indexed event directory, not a second before/after payload store.
CREATE TABLE TemporalEvent (
    EventID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    EntityType VARCHAR(64) NOT NULL,
    RecordIdentifier VARCHAR(1024) COLLATE utf8mb4_bin NOT NULL,
    RecordHash BINARY(32) GENERATED ALWAYS AS (UNHEX(SHA2(RecordIdentifier, 256))) STORED,
    OperationType VARCHAR(10) NOT NULL,
    ChangedAttributes JSON NOT NULL,
    ResponsibleUserID INT NULL,
    SessionAccount VARCHAR(288) COLLATE utf8mb4_bin NOT NULL,
    EventTimestamp DATETIME(6) NOT NULL,
    ContextID CHAR(36) NULL,
    Reason VARCHAR(500) NULL,
    CHECK (OperationType IN ('Insert', 'Update', 'Delete')),
    INDEX idx_TemporalEvent_EntityRecord (EntityType, RecordHash, EventID),
    INDEX idx_TemporalEvent_Entity (EntityType, EventID),
    INDEX idx_TemporalEvent_Actor (ResponsibleUserID, EventID),
    INDEX idx_TemporalEvent_Time (EventTimestamp, EventID)
) ENGINE=InnoDB;

DELIMITER //
CREATE PROCEDURE sp_BeginTemporalEvent(
    IN p_Entity VARCHAR(64), IN p_Key JSON, IN p_Operation VARCHAR(10),
    IN p_Changed JSON, IN p_PreviousTime DATETIME(6), IN p_Reason VARCHAR(500),
    OUT p_EventID BIGINT UNSIGNED, OUT p_Time DATETIME(6),
    OUT p_UserID INT, OUT p_Context CHAR(36)
)
BEGIN
    SET timestamp = 0;
    SET p_UserID = NULL;
    SET p_Context = NULL;
    -- Physical maintenance accounts have no on-behalf-of person. Do not use
    -- @app_user_id to manufacture one. Every other account uses migration 004.
    IF USER() NOT IN ('vsm_developer@localhost', 'vsm_admin@localhost') THEN
        CALL sp_ActorForWrite(p_UserID);
        SELECT MAX(ContextID) INTO p_Context FROM OperationContext
        WHERE ConnectionID = CONNECTION_ID() AND SessionAccount = USER();
    END IF;
    SET p_Time = UTC_TIMESTAMP(6);
    IF p_PreviousTime IS NOT NULL AND p_Time <= p_PreviousTime THEN
        SET p_Time = p_PreviousTime + INTERVAL 1 MICROSECOND;
    END IF;
    INSERT INTO TemporalWriteContext VALUES (CONNECTION_ID(), USER(), p_Entity);
    INSERT INTO TemporalEvent (EntityType, RecordIdentifier, OperationType, ChangedAttributes,
        ResponsibleUserID, SessionAccount, EventTimestamp, ContextID, Reason)
    VALUES (p_Entity, CAST(p_Key AS CHAR CHARACTER SET utf8mb4), p_Operation, p_Changed,
        p_UserID, USER(), p_Time, p_Context, p_Reason);
    SET p_EventID = LAST_INSERT_ID();
END //

CREATE TRIGGER trg_TemporalEvent_InsertGuard BEFORE INSERT ON TemporalEvent FOR EACH ROW
BEGIN
    IF NOT EXISTS (SELECT 1 FROM TemporalWriteContext WHERE ConnectionID = CONNECTION_ID()
                   AND SessionAccount = USER() AND EntityType = NEW.EntityType) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Temporal events require protected history maintenance';
    END IF;
END //
CREATE TRIGGER trg_TemporalEvent_UpdateGuard BEFORE UPDATE ON TemporalEvent FOR EACH ROW
BEGIN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Temporal events are immutable';
END //
CREATE TRIGGER trg_TemporalEvent_DeleteGuard BEFORE DELETE ON TemporalEvent FOR EACH ROW
BEGIN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Temporal events cannot be deleted';
END //
DELIMITER ;
SET timestamp = 0;
SET @history_snapshot_at = UTC_TIMESTAMP(6);
"""


def history_table(table, keys, columns):
    history = table + 'History'
    # Copy only column types first. CTAS otherwise requires defaults for every
    # non-selected NOT NULL history field even when WHERE FALSE copies no rows.
    return f"""
CREATE TABLE `{history}` ENGINE=InnoDB AS SELECT {quoted(columns)} FROM `{table}` WHERE FALSE;
ALTER TABLE `{history}`
    ADD COLUMN HistoryID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ADD COLUMN HistoryVersion BIGINT UNSIGNED NOT NULL,
    ADD COLUMN HistoryValidFrom DATETIME(6) NULL,
    ADD COLUMN HistoryValidTo DATETIME(6) NULL,
    ADD COLUMN HistoryRecordedAt DATETIME(6) NOT NULL,
    ADD COLUMN HistoryOrigin VARCHAR(10) NOT NULL,
    ADD COLUMN HistoryUserID INT NULL,
    ADD COLUMN HistorySessionAccount VARCHAR(288) COLLATE utf8mb4_bin NULL,
    ADD COLUMN HistoryContextID CHAR(36) NULL,
    ADD COLUMN HistoryReason VARCHAR(500) NULL,
    ADD COLUMN HistoryStartEventID BIGINT UNSIGNED NULL UNIQUE,
    ADD COLUMN HistoryEndEventID BIGINT UNSIGNED NULL UNIQUE,
    ADD COLUMN HistoryClosedByUserID INT NULL,
    ADD COLUMN HistoryClosedBySession VARCHAR(288) COLLATE utf8mb4_bin NULL,
    ADD COLUMN HistoryClosedContextID CHAR(36) NULL,
    ADD COLUMN HistoryCloseReason VARCHAR(500) NULL,
    ADD COLUMN HistoryCloseOperation VARCHAR(10) NULL,
    ADD COLUMN HistoryIsCurrent TINYINT GENERATED ALWAYS AS (IF(HistoryValidTo IS NULL, 1, NULL)) STORED,
    ADD CHECK (HistoryVersion > 0),
    ADD CHECK (HistoryOrigin IN ('Snapshot', 'Insert', 'Update')),
    ADD CHECK (HistoryValidTo IS NULL OR HistoryValidFrom IS NULL OR HistoryValidTo > HistoryValidFrom);
ALTER TABLE `{history}`
    ADD UNIQUE KEY uq_CurrentVersion ({quoted(keys)}, HistoryIsCurrent),
    ADD UNIQUE KEY uq_RecordVersion ({quoted(keys)}, HistoryVersion),
    ADD INDEX idx_Validity (HistoryValidFrom, HistoryValidTo);
INSERT INTO `{history}` ({quoted(columns)}, HistoryVersion, HistoryRecordedAt, HistoryOrigin)
SELECT {quoted(columns)}, 1, @history_snapshot_at, 'Snapshot' FROM `{table}`;
"""


def triggers(table, keys, ordinary, columns):
    history = table + 'History'
    where_old = ' AND '.join(f'`{c}` = OLD.`{c}`' for c in keys)
    where_new = ' AND '.join(f'`{c}` = NEW.`{c}`' for c in keys)
    context = f"EXISTS (SELECT 1 FROM TemporalWriteContext WHERE ConnectionID = CONNECTION_ID() AND SessionAccount = USER() AND EntityType = '{table}')"
    text = f"""
DELIMITER //
CREATE TRIGGER `trg_{table}_HistoryGuard_bi` BEFORE INSERT ON `{history}` FOR EACH ROW
BEGIN
    IF NOT {context} THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'History inserts require protected maintenance';
    END IF;
END //
CREATE TRIGGER `trg_{table}_HistoryGuard_bu` BEFORE UPDATE ON `{history}` FOR EACH ROW
BEGIN
    IF NOT {context} OR OLD.HistoryValidTo IS NOT NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'History versions are immutable outside protected closing';
    END IF;
END //
CREATE TRIGGER `trg_{table}_HistoryGuard_bd` BEFORE DELETE ON `{history}` FOR EACH ROW
BEGIN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'History records cannot be deleted';
END //
"""
    declarations = """    DECLARE v_Event BIGINT UNSIGNED;
    DECLARE v_Time DATETIME(6);
    DECLARE v_User INT;
    DECLARE v_Context CHAR(36);
    DECLARE v_Version BIGINT UNSIGNED DEFAULT 0;
    DECLARE v_Current BIGINT UNSIGNED DEFAULT NULL;
    DECLARE v_PreviousTime DATETIME(6) DEFAULT NULL;
    DECLARE v_KeyTime DATETIME(6) DEFAULT NULL;
    DECLARE v_Changed JSON;
"""
    for operation, suffix in (('Insert', 'ai'), ('Update', 'au'), ('Delete', 'ad')):
        text += f"CREATE TRIGGER `trg_{table}_History_{suffix}` AFTER {operation.upper()} ON `{table}` FOR EACH ROW\nBEGIN\n" + declarations
        if operation == 'Update':
            text += f"    IF NOT (CAST({row_json(ordinary, 'OLD.')} AS BINARY) <=> CAST({row_json(ordinary, 'NEW.')} AS BINARY)) THEN\n"
            text += "    SET v_Changed = JSON_ARRAY();\n"
            for c in ordinary:
                text += f"    IF NOT (CAST(OLD.`{c}` AS BINARY) <=> CAST(NEW.`{c}` AS BINARY)) THEN SET v_Changed = JSON_ARRAY_APPEND(v_Changed, '$', '{c}'); END IF;\n"
        else:
            text += "    SET v_Changed = JSON_ARRAY(" + ', '.join(f"'{c}'" for c in ordinary) + ");\n"
        if operation != 'Insert':
            text += f"""    SELECT HistoryID, HistoryVersion, COALESCE(HistoryValidFrom, HistoryRecordedAt)
    INTO v_Current, v_Version, v_PreviousTime FROM `{history}`
    WHERE {where_old} AND HistoryIsCurrent = 1 FOR UPDATE;
    IF v_Current IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Current temporal history version is missing';
    END IF;
"""
        if operation != 'Delete':
            # A current locking read also handles key reuse and primary-key changes.
            text += f"""    SET v_Version = 0;
    SELECT HistoryVersion, COALESCE(HistoryValidTo, HistoryValidFrom, HistoryRecordedAt)
    INTO v_Version, v_KeyTime FROM `{history}` WHERE {where_new}
    ORDER BY HistoryVersion DESC LIMIT 1 FOR UPDATE;
    IF v_KeyTime IS NOT NULL THEN
        SET v_PreviousTime = GREATEST(COALESCE(v_PreviousTime, v_KeyTime), v_KeyTime);
    END IF;
"""
        key = row_json(keys, 'OLD.' if operation == 'Delete' else 'NEW.')
        reason = "IF(NOT (OLD.QuantityOnHand <=> NEW.QuantityOnHand), @adj_reason, NULL)" if table == 'Part' and operation == 'Update' else 'NULL'
        text += f"    CALL sp_BeginTemporalEvent('{table}', {key}, '{operation}', v_Changed, v_PreviousTime, {reason}, v_Event, v_Time, v_User, v_Context);\n"
        if operation != 'Insert':
            text += f"""    UPDATE `{history}` SET HistoryValidTo = v_Time, HistoryEndEventID = v_Event,
        HistoryClosedByUserID = v_User, HistoryClosedBySession = USER(),
        HistoryClosedContextID = v_Context, HistoryCloseReason = {reason}, HistoryCloseOperation = '{operation}'
    WHERE HistoryID = v_Current;
"""
        if operation != 'Delete':
            text += f"""    INSERT INTO `{history}` ({quoted(columns)}, HistoryVersion, HistoryValidFrom, HistoryRecordedAt,
        HistoryOrigin, HistoryUserID, HistorySessionAccount, HistoryContextID, HistoryReason, HistoryStartEventID)
    VALUES ({quoted(columns, 'NEW.')}, v_Version + 1, v_Time, v_Time,
        '{operation}', v_User, USER(), v_Context, {reason}, v_Event);
"""
        text += f"    DELETE FROM TemporalWriteContext WHERE ConnectionID = CONNECTION_ID() AND EntityType = '{table}';\n"
        if operation == 'Update':
            text += '    END IF;\n'
        text += 'END //\n'
    return text + 'DELIMITER ;\n'


def event_query(table, columns, page=False):
    # Fix the hydration join order so even a large history starts from the
    # bounded ID page, rather than an optimizer-selected scan of all events.
    source = ('tmp_TemporalPageIDs page STRAIGHT_JOIN TemporalEvent e ON page.EventID = e.EventID'
              if page else 'TemporalEvent e')
    return f"""SELECT e.EventID, e.EntityType, e.RecordIdentifier, e.OperationType, e.ChangedAttributes,
    IF(old.HistoryID IS NULL, NULL, {row_json(columns, 'old.')}) AS PreviousValue,
    IF(new.HistoryID IS NULL, NULL, {row_json(columns, 'new.')}) AS NewValue,
    e.ResponsibleUserID, e.SessionAccount, e.EventTimestamp, e.ContextID, e.Reason
FROM {source}
LEFT JOIN `{table}History` old ON old.HistoryEndEventID = e.EventID
LEFT JOIN `{table}History` new ON new.HistoryStartEventID = e.EventID
WHERE e.EntityType = '{table}'"""


def generate():
    parts = [HEADER]
    specs = [(table, key.split(), cols.split(), generated.split()) for table, key, cols, generated in TABLES]
    for table, keys, ordinary, generated in specs:
        parts.append(history_table(table, keys, ordinary + generated))
    for table, keys, ordinary, generated in specs:
        parts.append(triggers(table, keys, ordinary, ordinary + generated))
    parts.append('\nCREATE VIEW vw_AuditTrail AS\n' + '\nUNION ALL\n'.join(event_query(t, c + g) for t, _, c, g in specs) + ';\n')
    parts.append("""
DELIMITER //
CREATE PROCEDURE sp_ListAuditTrail(
    IN p_Entity VARCHAR(64), IN p_RecordIdentifier JSON, IN p_UserID INT,
    IN p_From DATETIME(6), IN p_To DATETIME(6),
    IN p_BeforeEventID BIGINT UNSIGNED, IN p_Limit INT
)
READS SQL DATA
BEGIN
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        DROP TEMPORARY TABLE IF EXISTS tmp_TemporalPage, tmp_TemporalPageIDs;
        RESIGNAL;
    END;
    IF p_Limit IS NULL OR p_Limit < 1 OR p_Limit > 200
       OR (p_From IS NOT NULL AND p_To IS NOT NULL AND p_From >= p_To) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Invalid audit page size or date range';
    END IF;
    IF p_Entity IS NOT NULL AND p_Entity NOT IN (""" + ', '.join(f"'{t}'" for t, _, _, _ in specs) + """) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Unknown temporal audit entity';
    END IF;
    DROP TEMPORARY TABLE IF EXISTS tmp_TemporalPage, tmp_TemporalPageIDs;
    CREATE TEMPORARY TABLE tmp_TemporalPageIDs (EventID BIGINT UNSIGNED PRIMARY KEY) ENGINE=InnoDB;
    INSERT INTO tmp_TemporalPageIDs
    SELECT EventID FROM TemporalEvent
    WHERE (p_Entity IS NULL OR EntityType = p_Entity)
      AND (p_RecordIdentifier IS NULL OR
          (RecordHash = UNHEX(SHA2(CAST(p_RecordIdentifier AS CHAR CHARACTER SET utf8mb4), 256))
           AND RecordIdentifier = CAST(p_RecordIdentifier AS CHAR CHARACTER SET utf8mb4)))
      AND (p_UserID IS NULL OR ResponsibleUserID = p_UserID)
      AND (p_From IS NULL OR EventTimestamp >= p_From)
      AND (p_To IS NULL OR EventTimestamp < p_To)
      AND (p_BeforeEventID IS NULL OR EventID < p_BeforeEventID)
    ORDER BY EventID DESC LIMIT p_Limit;
    CREATE TEMPORARY TABLE tmp_TemporalPage AS SELECT * FROM vw_AuditTrail WHERE FALSE;
""")
    for table, _, columns, generated in specs:
        parts.append('    INSERT INTO tmp_TemporalPage\n' + event_query(table, columns + generated, page=True) + ';\n')
    parts.append("""    SELECT * FROM tmp_TemporalPage ORDER BY EventID DESC;
    DROP TEMPORARY TABLE tmp_TemporalPage, tmp_TemporalPageIDs;
END //
DELIMITER ;
SET @history_snapshot_at = NULL;
""")
    return '\n'.join(parts)


if __name__ == '__main__':
    print(generate(), end='')
